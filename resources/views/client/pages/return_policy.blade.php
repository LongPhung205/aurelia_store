<h2>1. Điều kiện áp dụng đổi trả</h2>
<p>Aurelia Store hỗ trợ đổi sản phẩm trong vòng <strong>07 ngày</strong> kể từ ngày nhận hàng (tính theo dấu bưu điện hoặc hệ thống của đơn vị vận chuyển) với các điều kiện sau:</p>
<ul>
    <li>Sản phẩm còn nguyên tem, mác, tag của nhà sản xuất.</li>
    <li>Sản phẩm chưa qua sử dụng, chưa qua giặt ủi, không bị bẩn, rách hay có mùi lạ (mùi nước hoa, mỹ phẩm...).</li>
    <li>Có hóa đơn mua hàng hoặc thông tin số điện thoại đặt hàng trùng khớp.</li>
    <li>Các sản phẩm <strong>KHÔNG</strong> áp dụng đổi trả: Đồ lót, phụ kiện (trang sức, băng đô...), sản phẩm trong chương trình khuyến mãi/giảm giá (Clearance Sale) trừ trường hợp lỗi từ phía Aurelia.</li>
</ul>

<h2>2. Hình thức đổi trả</h2>
<p>Chúng tôi hiện đang hỗ trợ các hình thức sau:</p>
<ul>
    <li><strong>Đổi Size / Màu:</strong> Hỗ trợ đổi sang kích thước hoặc màu sắc khác của cùng một mã sản phẩm (nếu còn hàng).</li>
    <li><strong>Đổi Mẫu:</strong> Khách hàng được quyền đổi sang một sản phẩm khác có giá trị bằng hoặc cao hơn sản phẩm cũ (Khách hàng thanh toán phần chênh lệch nếu có).</li>
    <li><strong>Hoàn tiền:</strong> Chỉ áp dụng hoàn tiền 100% đối với các sản phẩm bị lỗi kỹ thuật nghiêm trọng từ nhà sản xuất mà không có sản phẩm thay thế, hoặc giao sai sản phẩm.</li>
</ul>

<h2>3. Chi phí đổi trả</h2>
<ul>
    <li><strong>Miễn phí:</strong> Nếu sản phẩm bị lỗi từ nhà sản xuất hoặc do Aurelia giao sai hàng, chúng tôi sẽ chịu 100% phí vận chuyển 2 chiều.</li>
    <li><strong>Có tính phí:</strong> Nếu khách hàng muốn đổi size, đổi mẫu theo nhu cầu cá nhân, khách hàng vui lòng thanh toán phí vận chuyển 2 chiều.</li>
</ul>

<h2>4. Quy trình xử lý</h2>
<ol>
    <li>Liên hệ với Hotline hoặc Fanpage của Aurelia Store, cung cấp mã đơn hàng và hình ảnh/video tình trạng sản phẩm.</li>
    <li>Nhân viên CSKH sẽ xác nhận và hướng dẫn bạn đóng gói gửi sản phẩm về kho trung tâm.</li>
    <li>Sau khi nhận được hàng gửi về và kiểm tra đạt điều kiện, Aurelia sẽ tiến hành gửi lại sản phẩm mới hoặc hoàn tiền trong vòng 3-5 ngày làm việc.</li>
</ol>
